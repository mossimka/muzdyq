from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base
from .utils import utcnow

PHOTO_STATUSES = ("pending", "published", "hidden", "rejected")
POINT_TYPES = ("glacier", "water")


def _new_uuid() -> str:
    return str(uuid.uuid4())


class Point(Base):
    __tablename__ = "point"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    slug: Mapped[str] = mapped_column(String(80), unique=True, index=True, nullable=False)
    type: Mapped[str] = mapped_column(String(16), index=True, nullable=False)
    name_i18n: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False)
    description_i18n: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False)
    safety_note_i18n: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    lat: Mapped[float] = mapped_column(Float, nullable=False)
    lon: Mapped[float] = mapped_column(Float, nullable=False)
    elevation_m: Mapped[int | None] = mapped_column(Integer, nullable=True)
    coords_verified: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow
    )

    viewpoints: Mapped[list[Viewpoint]] = relationship(
        back_populates="point",
        cascade="all, delete-orphan",
        order_by="Viewpoint.id",
        lazy="selectin",
    )
    photos: Mapped[list[Photo]] = relationship(back_populates="point", cascade="all, delete-orphan")

    __table_args__ = (
        CheckConstraint("type IN ('glacier', 'water')", name="ck_point_type"),
    )


class Viewpoint(Base):
    __tablename__ = "viewpoint"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    point_id: Mapped[int] = mapped_column(
        ForeignKey("point.id", ondelete="CASCADE"), nullable=False, index=True
    )
    reference_photo: Mapped[str | None] = mapped_column(String(255), nullable=True)
    heading_deg: Mapped[int | None] = mapped_column(Integer, nullable=True)
    note_i18n: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow
    )

    point: Mapped[Point] = relationship(back_populates="viewpoints")
    photos: Mapped[list[Photo]] = relationship(back_populates="viewpoint")


class Photo(Base):
    __tablename__ = "photo"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_new_uuid)
    point_id: Mapped[int] = mapped_column(
        ForeignKey("point.id", ondelete="CASCADE"), nullable=False, index=True
    )
    viewpoint_id: Mapped[str | None] = mapped_column(
        ForeignKey("viewpoint.id", ondelete="SET NULL"), nullable=True, index=True
    )
    # Idempotency key generated by the client (UUID). Unique across the platform.
    client_uuid: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    taken_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    uploaded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow
    )
    width: Mapped[int] = mapped_column(Integer, nullable=False)
    height: Mapped[int] = mapped_column(Integer, nullable=False)
    bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    license: Mapped[str] = mapped_column(String(32), nullable=False, default="CC-BY-4.0")
    tags: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    phash: Mapped[str | None] = mapped_column(String(16), nullable=True)
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="pending", index=True)
    file_path: Mapped[str] = mapped_column(String(255), nullable=False)
    thumb_path: Mapped[str] = mapped_column(String(255), nullable=False)
    rejection_reason: Mapped[str | None] = mapped_column(String(255), nullable=True)
    ip_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    device_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)

    point: Mapped[Point] = relationship(back_populates="photos")
    viewpoint: Mapped[Viewpoint | None] = relationship(back_populates="photos")

    __table_args__ = (
        CheckConstraint(
            "status IN ('pending', 'published', 'hidden', 'rejected')", name="ck_photo_status"
        ),
        Index("ix_photo_point_taken", "point_id", "taken_at"),
        Index("ix_photo_point_status", "point_id", "status"),
    )
